/* LHB-75: the English strings the facelift adds or changes, for Sergio's review. Loads site/i18n.js from origin/main and from this
   tree in a vm (the file exposes window.LHB_I18N.T) and lists every en key that is new or whose text changed, beside its Spanish.
   usage: node evidence/m7-review-pack/en-strings.js BASE_REF OUT.md   (run from the repo root; BASE_REF like origin/main) */
'use strict';
const fs = require('fs'), vm = require('vm'), cp = require('child_process');
const [base, out] = process.argv.slice(2);
const load = src => { const w = {}; vm.runInNewContext(src, { window: w }); return w.LHB_I18N.T; };
const before = load(cp.execFileSync('git', ['show', base + ':site/i18n.js'], { encoding: 'utf8', maxBuffer: 1 << 26 }));
const now = load(fs.readFileSync('site/i18n.js', 'utf8'));
const cell = s => String(s).replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
const rows = [];
for (const k of Object.keys(now.en)) {
  const was = before.en[k];
  if (was === now.en[k]) continue;
  rows.push({ k, kind: was === undefined ? 'new' : 'changed', es: now.es[k] === undefined ? '(no Spanish key)' : now.es[k], en: now.en[k], was });
}
const gone = Object.keys(before.en).filter(k => !(k in now.en));
const head = cp.execFileSync('git', ['rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
const baseSha = cp.execFileSync('git', ['rev-parse', base], { encoding: 'utf8' }).trim();
let md = '# English strings to review (facelift)\n\n';
md += 'Generated by evidence/m7-review-pack/en-strings.js from site/i18n.js at ' + head + ', compared with ' + base + ' at ' + baseSha + '.\n\n';
md += 'Counting basis: keys of the `en` table whose text is new or differs from ' + base + '. ';
md += rows.filter(r => r.kind === 'new').length + ' new, ' + rows.filter(r => r.kind === 'changed').length + ' changed, ' + gone.length + ' removed; ';
md += Object.keys(now.en).length + ' en keys in all.\n\n';
md += 'For each row: is the English natural and correct, and does it say the same thing as the Spanish? Mark the row OK or write the better wording.\n\n';
md += '| # | Key | Kind | Spanish | English | Before |\n|---|---|---|---|---|---|\n';
rows.forEach((r, i) => { md += '| ' + (i + 1) + ' | `' + r.k + '` | ' + r.kind + ' | ' + cell(r.es) + ' | ' + cell(r.en) + ' | ' + (r.was === undefined ? '' : cell(r.was)) + ' |\n'; });
if (gone.length) md += '\nRemoved keys: ' + gone.map(k => '`' + k + '`').join(', ') + '\n';
fs.writeFileSync(out, md);
console.log('rows ' + rows.length + ' (new ' + rows.filter(r => r.kind === 'new').length + ', changed ' + rows.filter(r => r.kind === 'changed').length + '), removed ' + gone.length + ', en keys ' + Object.keys(now.en).length + ' -> ' + out);
